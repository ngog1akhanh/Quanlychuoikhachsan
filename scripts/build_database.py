"""Đóng gói script nguồn trong Database/Scripts thành MỘT file cài đặt: Database/Install/hotel_management_full.sql.

File gồm schema + phần mở rộng API + ràng buộc + quyền + toàn bộ dữ liệu demo.
Chạy:  python scripts/build_database.py          -> sinh lại file
       python scripts/build_database.py --check  -> kiểm tra file đã cập nhật theo script nguồn chưa
"""
from argparse import ArgumentParser
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATABASE = ROOT / "Quanlychuoikhachsan/Database"
OUTPUT = DATABASE / "Install/hotel_management_full.sql"
# Phần cấu trúc (thứ tự bắt buộc). add_operational_api_support.sql đã gồm ràng buộc/view bổ sung.
SOURCES = (
    "hotel_management_final_food_inventory.sql",
    "add_vietqr_payment_order.sql",
    "add_operational_api_support.sql",
    "seed_api_permissions.sql",
)
# Dữ liệu demo (thứ tự bắt buộc: seed_demo trước).
DEMO_SEEDS = (
    "seed_demo.sql",
    "seed_operations_demo.sql",
    "seed_kho_demo.sql",
    "seed_thong_ke.sql",
)
# Mốc để test MySQL cắt lấy phần cấu trúc (không dữ liệu demo); đừng đổi nội dung dòng này.
DEMO_MARKER = "-- ===== DEMO DATA BELOW ====="


def build(name: str) -> str:
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", name):
        raise ValueError("Tên database chỉ gồm chữ thường, số và dấu _, bắt đầu bằng chữ.")
    parts = [
        "-- GENERATED by scripts/build_database.py; do not edit this file directly.",
        "-- Tạo database MỚI + dữ liệu demo (tài khoản demo, phòng, booking, kho, thống kê).",
        "-- Mật khẩu mọi tài khoản demo: 12345 (xem 'tai khoan test demo.txt').",
        "-- Chạy bằng MySQL Workbench (Execute all) hoặc mysql client, KHÔNG dùng --force.",
        "-- MySQL >= 8.0.16 / MariaDB >= 10.4; utf8mb4; thời điểm lưu UTC.",
        "-- Không DROP database: database đã tồn tại thì dừng ngay ở lệnh đầu tiên.",
        f"CREATE DATABASE `{name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
        f"USE `{name}`;",
        "SET NAMES utf8mb4;",
        "SET time_zone = '+00:00';",
        "SET SESSION sql_mode = 'STRICT_TRANS_TABLES,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION,ONLY_FULL_GROUP_BY';",
    ]
    for filename in SOURCES:
        sql = (DATABASE / "Scripts" / filename).read_text(encoding="utf-8-sig")
        if filename == SOURCES[0]:
            sql, count = re.subn(
                r"CREATE DATABASE IF NOT EXISTS hotel_management.*?SET time_zone = '\+07:00';",
                "", sql, count=1, flags=re.S,
            )
            if count != 1:
                raise ValueError("Header schema gốc đã thay đổi; cần kiểm tra lại bộ đóng gói.")
        # Giữ phần lẻ giây mà EF Core ghi vào các cột thời điểm.
        sql = re.sub(r"\bDATETIME\b(?!\s*\()", "DATETIME(6)", sql)
        sql = re.sub(r"\bTIME\b(?!\s*\()", "TIME(6)", sql)
        sql = re.sub(r"\bCURRENT_TIMESTAMP\b(?!\s*\()", "CURRENT_TIMESTAMP(6)", sql)
        parts.extend([f"\n-- SOURCE: {filename}", sql.rstrip()])
    parts.append("\n" + DEMO_MARKER)
    for filename in DEMO_SEEDS:
        sql = (DATABASE / "Scripts" / filename).read_text(encoding="utf-8-sig")
        parts.extend([f"\n-- SOURCE: {filename}", "SET NAMES utf8mb4;", sql.rstrip()])
    parts.extend([
        "\n-- Database và dữ liệu demo đã sẵn sàng.",
        "SELECT DATABASE() AS database_name, 'READY_WITH_DEMO_DATA' AS installation_status;",
        "",
    ])
    return "\n".join(parts)


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    # Trùng Database= trong Quanlychuoikhachsan/appsettings.json để máy mới chạy được ngay.
    parser.add_argument("--database", default="hotel_management")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="Kiểm tra file đã đóng gói có cập nhật không.")
    parser.add_argument("--full", action="store_true", help="Giữ để tương thích lệnh cũ; luôn sinh bản đầy đủ.")
    args = parser.parse_args()
    sql = build(args.database)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != sql:
            raise SystemExit("SQL bundle chưa cập nhật; chạy scripts/build_database.py.")
        print("SQL bundle is up to date.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(sql, encoding="utf-8", newline="\n")
        print(f"Created {args.output}")


if __name__ == "__main__":
    main()
